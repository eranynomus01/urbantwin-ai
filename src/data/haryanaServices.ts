export const getServicesByCity = (cityId: string): MunicipalServiceAsset[] => {
  return HARYANA_MUNICIPAL_SERVICES.filter(s => s.cityId === cityId);
};

export const getServicesByType = (serviceType: string, cityId?: string): MunicipalServiceAsset[] => {
  return HARYANA_MUNICIPAL_SERVICES.filter(s => {
    const matchType = s.serviceType === serviceType;
    return cityId ? (matchType && s.cityId === cityId) : matchType;
  });
};
